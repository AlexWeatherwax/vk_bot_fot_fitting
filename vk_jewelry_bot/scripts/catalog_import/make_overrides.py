def main() -> None:
    items = {(i["section"], i["title"]): i for i in json.loads(ITEMS_JSON.read_text(encoding="utf-8"))}
    out, problems = {}, []
    for (section, title), idx in CHOICE.items():
        item = items.get((section, title))
        if item is None:
            problems.append(f"нет такого товара: {section}/{title}")
            continue
        if idx >= len(item["photos"]):
            problems.append(f"{section}/{title}: индекс {idx} >= {len(item['photos'])} фото")
            continue
        out[item["key"]] = idx
    missing = [f"{s}/{t}" for (s, t) in items if (s, t) not in CHOICE]
    OVERRIDES_JSON.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Записано выборов: {len(out)} из {len(items)} товаров")
    for p in problems:
        print("  ОШИБКА:", p)
    for m in missing:
        print("  без ручного выбора (останется автоматический):", m)


if __name__ == "__main__":
    main()
